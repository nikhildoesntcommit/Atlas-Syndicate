  F.SMALL = SMALL; F.BIG = BIG;

  function atlas(font, col) {
    if (font.cache[col]) return font.cache[col];
    const c = document.createElement('canvas');
    c.width = font.chars.length * (font.w + 1); c.height = font.h;
    const x = c.getContext('2d');
    x.fillStyle = AS.PALETTE[col];
    font.chars.forEach((ch, i) => {
      const g = font.src[ch];
      for (let y = 0; y < font.h; y++) for (let xx = 0; xx < font.w; xx++) if (g[y] && g[y][xx] === '#') x.fillRect(i * (font.w + 1) + xx, y, 1, 1);
    });
    font.cache[col] = c;
    return c;
  }

  F.width = function (s, big, scale) {
    const f = big ? fonts.big : fonts.small;
    s = String(s);
    return Math.max(0, s.length * f.adv - 1) * (scale || 1);
  };
  /**
   * Draw text. opts: align ('left'|'center'|'right'), scale (int), shadow (bool, default true), big (bool),
   * shadowCol (palette index). Returns drawn width.
   */
  F.draw = function (ctx, str, x, y, col, opts) {
    const o = opts || {};
    const f = o.big ? fonts.big : fonts.small;
    const sc = o.scale || 1;
    str = String(str).toUpperCase();
    if (o.big) str = str.replace(/×/g, 'x');
    const w = F.width(str, o.big, sc);
    const x0 = Math.round(o.align === 'center' ? x - w / 2 : o.align === 'right' ? x - w : x), y0 = Math.round(y);
    const draw = (atl, ox, oy) => {
      for (let i = 0; i < str.length; i++) {
        const ch = str[i];
        if (ch === ' ') continue;
        let gi = f.idx[ch];
        if (gi === undefined) gi = f.idx[ch.toUpperCase()];
        if (gi === undefined) gi = f.idx['?'];
        ctx.drawImage(atl, gi * (f.w + 1), 0, f.w, f.h, x0 + ox + i * f.adv * sc, y0 + oy, f.w * sc, f.h * sc);
      }
    };
    if (o.shadow !== false) draw(atlas(f, o.shadowCol === undefined ? 0 : o.shadowCol), sc, sc);
    draw(atlas(f, col), 0, 0);
    return w;
  };
  /** Industrial logo lettering: big font, stacked colour bands, soot outline. */
  F.logo = function (ctx, str, x, y, scale, bands) {
    const f = fonts.big;
    str = String(str).toUpperCase();
    const w = F.width(str, true, scale), x0 = Math.round(x - w / 2), y0 = Math.round(y);
    bands = bands || [31, 14, 13, 13, 12, 12, 11];
    const layer = (cfn, ox, oy) => {
      for (let i = 0; i < str.length; i++) {
        const g = f.src[str[i]];
        if (!g) continue;
        for (let gy = 0; gy < 7; gy++) for (let gx = 0; gx < 5; gx++) if (g[gy][gx] === '#') {
          ctx.fillStyle = AS.PALETTE[cfn(gy)];
          ctx.fillRect(x0 + ox + (i * 6 + gx) * scale, y0 + oy + gy * scale, scale, scale);
        }
      }
    };
    for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1], [2, 2], [scale, scale]]) layer(() => 0, ox, oy);
    layer(gy => bands[gy], 0, 0);
    ctx.fillStyle = AS.PALETTE[14];   // bevel highlight on top rows
    return w;
  };
